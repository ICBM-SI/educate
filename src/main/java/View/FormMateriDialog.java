    private void btnPilihActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPilihActionPerformed
    javax.swing.JFileChooser fc = new javax.swing.JFileChooser();
if (rdoVideo.isSelected()) {
    fc.setFileFilter(new javax.swing.filechooser.FileNameExtensionFilter("Video (mp4, mkv)", "mp4", "mkv"));
} else {
    fc.setFileFilter(new javax.swing.filechooser.FileNameExtensionFilter("Dokumen (pdf, txt, docx)", "pdf", "txt", "docx"));
}
if (fc.showOpenDialog(this) == javax.swing.JFileChooser.APPROVE_OPTION) {
    txtPilih.setText(fc.getSelectedFile().getAbsolutePath());
}            // TODO add your handling code here:
    }//GEN-LAST:event_btnPilihActionPerformed

    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
    if (!rdoTeks.isSelected() && !rdoVideo.isSelected()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Pilih jenis materi dulu");
    return;
}
if (txtJudul.getText().isBlank()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Judul wajib diisi");
    return;
}
if (txtTopik.getText().isBlank()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Topik wajib diisi");
    return;
}
if (txtPilih.getText().isBlank()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Pilih file konten dulu");
    return;
}
disimpan = true;   // penanda bahwa pengguna menekan Simpan
dispose();        // TODO add your handling code here:
    }//GEN-LAST:event_btnSimpanActionPerformed

