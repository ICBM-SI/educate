    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
    if (txtPaket.getText().isBlank()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Paket soal wajib diisi");
    return;
}
if (txtTopik.getText().isBlank()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Judul wajib diisi");
    return;
}
if (getTingkat().isEmpty() || getTingkat().equals("null")) {
    javax.swing.JOptionPane.showMessageDialog(this, "Kelas wajib diisi");
    return;
}

if (txtPertanyaan.getText().isBlank()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Isi pertanyaan dulu");
    return;
}
disimpan = true;   // penanda bahwa pengguna menekan Simpan
dispose();        // TODO add your handling code here:
    }//GEN-LAST:event_btnSimpanActionPerformed

