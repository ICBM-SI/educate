    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
    if (txtJadwal.getText().isBlank()) {
    javax.swing.JOptionPane.showMessageDialog(this, "Nama tidak boleh kosong");
    return;
    }
    if (txtJadwal.getText().trim().length() > 100) {
        javax.swing.JOptionPane.showMessageDialog(this, "Nama terlalu panjang (maksimal 100 karakter)");
        return;
    }
    if (getStatus().isEmpty() || getStatus().equals("null")) {
    javax.swing.JOptionPane.showMessageDialog(this, "Kelas wajib diisi");
    return;
}
    disimpan = true;
    dispose();       // TODO add your handling code here:
    }//GEN-LAST:event_btnSimpanActionPerformed

