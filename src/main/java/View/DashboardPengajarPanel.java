    public void tampilkanHalaman(String nama) {
    ((java.awt.CardLayout) panelKonten.getLayout()).show(panelKonten, nama);
    if ("beranda".equals(nama)) beranda.muatData();
    if ("editProfil".equals(nama)) editProfil.muatProfil();
    if ("pelajar".equals(nama)) pelajar.refreshData();
    if ("kelas".equals(nama)) kelas.refreshData();
    if ("soal".equals(nama)) soal.refreshData();
}

    
